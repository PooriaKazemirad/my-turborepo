/** Keep prop values as literal unions while selecting from display labels. */
export function choice<const T extends string>(
  label: string,
  values: readonly T[],
  fallback: T
): T {
  const value = label.toLowerCase().replaceAll(" ", "-")
  return values.find((item) => item === value) ?? fallback
}
